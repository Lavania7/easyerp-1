'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.EASYERP_PLAYWRIGHT_MODULE||'playwright');
const base=process.env.EASYERP_URL||'http://127.0.0.1:8092';
const out=process.env.EASYERP_DATABASE_OUTPUT||path.resolve(__dirname,'../reports/database-manager');
(async()=>{
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const checks=[], errors=[], writes=[];
  const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.on('pageerror',error=>errors.push(error.message));
    page.on('request',request=>{if(request.method()!=='GET'&&request.url().includes('/api/'))writes.push(request.url());});
    await page.goto(base+'/?mode=demo');
    await page.waitForFunction(()=>window.easyerpDatabaseManager&&window.ERPUI);
    const registry=await (await page.request.get(base+'/api/databases')).json();
    const migrated=registry.migration==='cutover';
    if(process.env.EASYERP_EXPECT_MIGRATED){
      check('migration record reports retained source',migrated&&registry.source_retained);
      const old=registry.nodes.find(node=>node.kind==='retained-source');
      const active=registry.nodes.find(node=>node.id==='active-live');
      check('restored relationship preserves old source',old?.port===55433&&active?.port===55434&&active.parent_id===old.id&&active.relation==='restored-copy');
    }
    await page.locator('#source-toggle').click();
    await page.locator('#database-manager-open').click();
    const dialog=page.locator('#database-manager');
    await dialog.locator('[data-db-node]').first().waitFor();
    check('real registry has three roots',(await dialog.locator('[data-db-node]').count())>=3);
    check('manager dialog visible',await dialog.isVisible());
    check('current live location visible',(await dialog.locator('[data-db-detail]').innerText()).includes('pgdata'));
    check('no blur',await dialog.evaluate(node=>getComputedStyle(node).backdropFilter==='none'));
    check('source menu closed',await page.locator('#source-menu').isHidden());
    await dialog.locator('[data-db-new]').click();
    await dialog.locator('input[name=label]').fill('新空白版本');
    await dialog.locator('form').evaluate(form=>form.requestSubmit());
    await dialog.locator('[data-db-notice]').waitFor({state:'visible'});
    check('folder required',(await dialog.locator('[data-db-notice]').innerText()).includes('文件夹'));
    await page.route('**/api/databases/folder',route=>route.fulfill({json:{cancelled:false,folder:'D:\\test-only',folder_ticket:'browser-fixture'}}));
    await page.route('**/api/databases/preview',route=>route.fulfill({json:{plan_id:'fixture',directory:'D:\\test-only\\empty',port:55490,effects:['空白结构派生']}}));
    await dialog.locator('[data-db-folder]').click();
    await page.waitForFunction(()=>document.querySelector('[data-db-folder-label]')?.textContent.includes('test-only'));
    await dialog.locator('button[type=submit]').click();
    await dialog.locator('[data-db-create]').waitFor();
    check('preview renders new target',(await dialog.locator('[data-db-preview]').innerText()).includes('55490'));
    await dialog.locator('input[name=label]').fill('修改后重新预览');
    check('editing form invalidates plan',(await dialog.locator('[data-db-create]').count())===0);
    await dialog.locator('[data-db-migration]').click();
    await page.waitForFunction(()=>document.querySelector('[data-db-detail]')?.textContent.includes('D:\\database\\easyerp-live'));
    check('real migration status is accurate',(await dialog.locator('[data-db-detail]').innerText()).includes(migrated?'旧源保留':'尚未执行'));
    await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
    await dialog.locator('[data-db-close]').last().click();
    await page.locator('#language-toggle').click();
    await page.evaluate(()=>window.easyerpDatabaseManager.open());
    await dialog.locator('[data-db-node]').first().waitFor();
    await page.waitForFunction(()=>document.querySelector('#database-manager-title')?.textContent==='Database manager');
    check('English translated',await dialog.locator('#database-manager-title').textContent()==='Database manager');
    await dialog.locator('[data-db-close]').last().click();
    await page.locator('#language-toggle').click();
    await page.evaluate(()=>window.easyerpDatabaseManager.open());
    await page.waitForFunction(()=>document.querySelector('#database-manager-title')?.textContent==='Datenbankverwaltung');
    check('German translated',await dialog.locator('#database-manager-title').textContent()==='Datenbankverwaltung');
    await dialog.locator('[data-db-close]').last().click();
    await page.locator('#language-toggle').click();
    await page.setViewportSize({width:400,height:700});
    await page.evaluate(()=>{document.documentElement.dataset.theme='dark';window.easyerpDatabaseManager.open();});
    await dialog.locator('[data-db-node]').first().waitFor();
    await dialog.locator('[data-db-new]').click();
    const box=await dialog.boundingBox();
    check('narrow dialog in viewport',box.x>=0&&box.y>=0&&box.x+box.width<=400&&box.y+box.height<=700);
    check('dark palette inherits',await dialog.evaluate(node=>getComputedStyle(node).backgroundColor!=='rgb(255, 255, 255)'));
    await page.screenshot({path:path.join(out,'narrow-dark.png'),fullPage:true});
    await page.keyboard.press('Escape');
    check('Escape closes',!await dialog.isVisible());
    check('browser errors absent',errors.length===0);
    check('only mocked folder/preview writes',writes.every(url=>/\/api\/databases\/(folder|preview)$/.test(url)));
    fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({checks,errors,writes,mocked:['folder','preview'],real_database_writes:0},null,2));
    process.stdout.write(JSON.stringify({checks:checks.length,errors:errors.length,real_database_writes:0,out})+'\n');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
