'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { chromium } = require(process.env.EASYERP_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.EASYERP_URL, output = process.env.EASYERP_TABLE_OUTPUT, run = process.env.EASYERP_TABLE_RUN;
const passed = [], check = (name, condition = true) => { assert.ok(condition, name); passed.push(name); console.log('PASS: ' + name); };
(async () => {
  assert.ok(base && output && run, 'Run through test_table_tools.py --integration --browser');
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = [], posts = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/entry/bulk') posts.push(JSON.parse(request.postData())); });
    const url = mode => base + '/?mode=' + mode + '&search=' + run + '&start=2026-01-01&end=2026-12-31#/data?department=finance&object=' + encodeURIComponent('finance.资金流水表') + '&reference=1';
    const ready = () => page.locator('.table-tools-query').waitFor();
    await page.goto(url('demo')); await ready();
    check('real release page mounts whole-result filter tools', await page.locator('.table-tools-query').count() === 1);
    await page.locator('[data-table-edit-toggle]').click();
    const rows = page.locator('[data-tool-row-select]');
    check('checkboxes select actual authoritative rows', await rows.count() === 30);
    await rows.first().check();
    await page.locator('[data-paging="1"]').click(); await ready();
    check('an explicit selection persists across pages', (await page.locator('[data-tool-selected]').textContent()).includes('1 / 100'));
    await page.locator('[data-tool-select-page]').check();
    check('select this page adds only the five displayed rows', (await page.locator('[data-tool-selected]').textContent()).includes('6 / 100'));
    await page.locator('[data-tool-bulk-open]').click(); await page.locator('[data-tool-batch-field]').waitFor();
    const field = page.locator('[data-tool-batch-field]');
    check('primary and currency fields are absent from batch choices', await field.locator('option[value="资金记录ID"],option[value="币种"]').count() === 0);
    await field.selectOption('交易摘要');
    await page.locator('[data-tool-batch-input]').fill(run + ' browser batch');
    await page.screenshot({ path: path.join(output, 'table-tools-batch-desktop.png'), fullPage: true });
    await page.locator('[data-table-edit-toggle]').click();
    check('leaving edit mode hides the batch editor', !await page.locator('.table-tools-batch').isVisible());
    await page.locator('[data-table-edit-toggle]').click();
    const save = page.waitForResponse(response => new URL(response.url()).pathname === '/api/entry/bulk');
    await page.locator('[data-tool-batch-save]').click();
    const saved = await save, response = await saved.json();
    assert.equal(saved.status(), 200, JSON.stringify(response));
    await ready();
    check('UI batch sends six captured row versions and exact content', posts.at(-1).records.length === 6 && posts.at(-1).records.every(row => /^\d+$/.test(row.version)) && posts.at(-1).value === run + ' browser batch');
    check('selection clears after batch commit', (await page.locator('[data-tool-selected]').textContent()).includes('0 / 100'));
    await page.locator('.table-tools-query summary').click();
    await page.locator('[data-tool-add-filter]').click();
    await page.locator('[data-tool-filter-field]').selectOption('金额');
    await page.locator('[data-tool-filter-op]').selectOption('gte');
    await page.locator('[data-tool-filter-value]').fill('10.0000');
    await page.locator('[data-tool-sort]').selectOption('金额');
    await page.locator('[data-tool-direction]').selectOption('desc');
    const query = page.waitForResponse(response => new URL(response.url()).pathname === '/api/explore' && new URL(response.url()).searchParams.get('table_filters')?.includes('gte'));
    await page.locator('.table-tools-query [type=submit]').click();
    const result = await (await query).json(); await ready();
    check('frontend submits filters and sorting for all matching records', result.total[0].count === 3 && result.rows[0]['金额'] === '9999999999999999.9999');
    const downloadPromise = page.waitForEvent('download'); await page.locator('#export').click();
    const download = await downloadPromise, csv = fs.readFileSync(await download.path(), 'utf8');
    check('export follows the displayed query rather than its current page', csv.includes('9999999999999999.9999') && csv.split('\n').filter(Boolean).length === 4 && !csv.includes('_table_version'));
    if (await page.locator('[data-table-edit-toggle]').getAttribute('aria-pressed') !== 'true') await page.locator('[data-table-edit-toggle]').click();
    await page.locator('[data-tool-row-select]').first().check();
    await page.locator('.table-tools-query summary').click();
    await page.locator('[data-tool-reset]').click(); await ready();
    check('changing the query clears selection', (await page.locator('[data-tool-selected]').textContent()).includes('0 / 100'));
    if (await page.locator('[data-table-edit-toggle]').getAttribute('aria-pressed') !== 'true') await page.locator('[data-table-edit-toggle]').click();
    await page.locator('[data-tool-row-select]').first().check();
    await page.evaluate(() => { state.mode = 'live'; render(); }); await ready();
    check('switching source clears selected records and batch panel', await page.locator('[data-tool-row-select]').count() === 0 && await page.locator('.table-tools-batch').count() === 0 && (await page.locator('[data-tool-selected]').textContent()).includes('0 / 100'));
    await page.goto(url('demo')); await ready();
    await page.locator('#language-toggle').click();
    await page.waitForFunction(() => document.querySelector('.table-tools-query summary').textContent.includes('Field filters'));
    check('English controls translate');
    await page.locator('[data-table-edit-toggle]').click(); await page.locator('[data-tool-row-select]').first().check();
    await page.locator('[data-tool-bulk-open]').click(); await page.locator('[data-tool-batch-field]').waitFor();
    await page.locator('[data-tool-batch-field]').selectOption('交易摘要');
    await page.locator('[data-tool-batch-input]').fill(run + ' language draft');
    await page.locator('#language-toggle').click();
    await page.waitForFunction(() => document.querySelector('.table-tools-query summary').textContent.includes('Feldfilter'));
    check('German controls translate');
    check('an English-created batch editor translates to German without losing its draft', (await page.locator('[data-tool-batch-save]').textContent()).includes('Gesamte Auswahl speichern') && await page.locator('[data-tool-batch-input]').inputValue() === run + ' language draft');
    await page.locator('#language-toggle').click();
    check('the same batch editor returns to Chinese with its original content', (await page.locator('[data-tool-batch-save]').textContent()).includes('保存整批') && await page.locator('[data-tool-batch-input]').inputValue() === run + ' language draft');
    await page.locator('[data-tool-batch-field]').selectOption('金额');
    await page.locator('[data-tool-batch-input]').fill('9876543210123456.4321');
    let dropped = false;
    await page.route('**/api/entry/bulk?*', async route => {
      if (dropped) return route.continue();
      dropped = true;
      await route.fetch(); await route.abort('failed');
    });
    const original = posts.length;
    await page.locator('[data-tool-batch-save]').click();
    await page.waitForFunction(() => document.querySelector('[data-tool-batch-save]')?.textContent.includes('重试原批次'));
    const first = posts[original];
    await page.locator('[data-tool-batch-save]').click();
    await page.locator('.table-tools-batch').waitFor({ state: 'detached' });
    check('lost response retries the original immutable batch request', posts.length === original + 2 && JSON.stringify(first) === JSON.stringify(posts[original + 1]) && first.value === '9876543210123456.4321');
    await ready();
    await page.locator('.table-tools-query summary').click(); await page.locator('[data-tool-add-filter]').click();
    await page.setViewportSize({ width: 390, height: 844 });
    check('query tools fit narrow screens without widening the page', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: path.join(output, 'table-tools-mobile.png'), fullPage: true });
    while (await page.locator('html').getAttribute('data-theme') !== 'dark') await page.locator('#theme-toggle').click();
    await page.screenshot({ path: path.join(output, 'table-tools-dark.png'), fullPage: true });
    check('no backdrop blur added', await page.evaluate(() => [...document.querySelectorAll('.table-tools-query,.table-tools-batch')].every(element => ['none', ''].includes(getComputedStyle(element).backdropFilter))));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(base + '/?mode=demo&search=' + run + '#/archive?department=legal&object=' + encodeURIComponent('legal.公司主体档案表') + '&reference=1'); await ready();
    await page.locator('[data-table-edit-toggle]').click(); await page.locator('[data-tool-row-select]').first().check();
    await page.locator('[data-tool-bulk-open]').click(); await page.locator('[data-tool-batch-field]').waitFor();
    await page.locator('[data-tool-batch-field]').selectOption('成立日期');
    const beforeDate = posts.length;
    await page.locator('[data-tool-batch-save]').click();
    check('an optional date requires a valid value or an explicit NULL choice', posts.length === beforeDate && await page.locator('[data-tool-batch-input]').evaluate(input => input.required && !input.checkValidity()));
    await page.locator('[data-tool-batch-null]').selectOption('null');
    const nullSaved = page.waitForResponse(response => new URL(response.url()).pathname === '/api/entry/bulk');
    await page.locator('[data-tool-batch-save]').click();
    assert.equal((await nullSaved).status(), 200);
    check('explicit optional date NULL is sent without date conversion', posts.at(-1).value === null);
    check('no uncaught browser errors', errors.length === 0);
    fs.writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify({ status: 'PASS', passed, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
