"""Real browser/HTTP/SQL table editing. Synthetic records only enter the demo DB.

Needs Node.js, Playwright (NODE_PATH or EASYERP_PLAYWRIGHT_MODULE), and Edge
(or EASYERP_BROWSER_CHANNEL). No browser is installed by this test.
"""
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.parse import urlencode
from datetime import datetime, timezone
import argparse
import json
import os
import subprocess
import sys
import uuid

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:8092')
parser.add_argument('--node', default='node')
parser.add_argument('--screenshot', type=Path)
args = parser.parse_args()
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
from easyerp import ERP, literal as L

erp = ERP()
demo = erp.c['database']+'_ui_demo'
run = 'qa_table_'+uuid.uuid4().hex[:12]
customer, fund = run+'_customer', run+'_fund'
new_customer, new_fund = run+'_new_customer', run+'_new_fund'
report = ROOT/'reports/table-edit-tests.json'
before = erp.data_signature(erp.c['database'])
token = ''


def call(path, payload=None):
    request = Request(args.url+'/api/entry/'+path+'?'+urlencode({'mode': 'demo'}),
                      data=None if payload is None else json.dumps(payload, ensure_ascii=False).encode(),
                      headers={'Content-Type': 'application/json', 'X-EasyERP-Token': token})
    with urlopen(request, timeout=30) as response:
        return json.load(response)


def create(key, values, suffix):
    return call('save', {'request_id': run+suffix, 'object': key, 'values': values})


try:
    metadata = call('meta')
    assert metadata['mode'] == 'demo'
    token = metadata['token']
    create('sales.客户档案表', {'客户ID': customer, '客户名称': '逐行编辑隔离验收',
                             '客户来源标识': run, '产业分类': '待修改', '确认日期': '2026-10-30'}, '_create_customer')
    create('finance.资金流水表', {'资金记录ID': fund, '账户ID': 'account',
                             '发生时间': '2026-10-30T04:00:00+00:00', '金额': '10.1234',
                             '收支方向': '收入', '交易摘要': '逐行编辑演示样例'}, '_create_fund')
    fixture = {'url': args.url, 'token': token, 'run': run, 'customer': customer,
               'fund': fund, 'newCustomer': new_customer, 'newFund': new_fund, 'result': str(report),
               'screenshot': str(args.screenshot.resolve()) if args.screenshot else None}
    env = {**os.environ, 'EASYERP_TABLE_FIXTURE': json.dumps(fixture, ensure_ascii=False)}
    subprocess.run([args.node, str(ROOT/'tests/test_table_edit.cjs')], env=env, check=True, timeout=240)
    # Independently read PostgreSQL using the read-only role after browser saves.
    actual = erp.sql(f'SELECT "客户名称"||\'|\'||("产业分类" IS NULL)::text FROM sales."客户档案表" WHERE "客户ID"={L(customer)}',
                     db=demo, role='easyerp_read').stdout.strip()
    assert actual == '表格编辑最终值|true', actual
    actual = erp.sql(f'SELECT "金额"::text||\'|\'||"交易摘要" FROM finance."资金流水表" WHERE "资金记录ID"={L(fund)}',
                     db=demo, role='easyerp_read').stdout.strip()
    assert actual == '9007199254740993.1234|丢失响应后幂等重试', actual
    audit_count = erp.sql(f"SELECT count(*) FROM erp_ops.frontend_entry_audit a WHERE a.changes @> jsonb_build_array(jsonb_build_object('operation','update','object','finance.资金流水表','after',jsonb_build_object('资金记录ID',{L(fund)},'交易摘要','丢失响应后幂等重试')))",
                          db=demo, role='easyerp_read').stdout.strip()
    assert audit_count == '1', 'Retry created duplicate audit rows'
    created_count = erp.sql(f'SELECT count(*) FROM sales."客户档案表" WHERE "客户来源标识"={L(run)}',
                            db=demo, role='easyerp_read').stdout.strip()
    assert created_count == '3', 'Expected fixture, custom ID and exactly one automatic ID customer'
    new_audit_count = erp.sql(f"SELECT count(*) FROM erp_ops.frontend_entry_audit a WHERE a.changes @> jsonb_build_array(jsonb_build_object('operation','create','object','sales.客户档案表','after',jsonb_build_object('客户名称',{L(run+'_auto')})))",
                              db=demo, role='easyerp_read').stdout.strip()
    assert new_audit_count == '1', 'Create retry duplicated the audit'
finally:
    # Exact IDs are generated by this run; no formal records or other demo rows are removed.
    erp.sql(f'''BEGIN;
      DELETE FROM finance."资金流水表" WHERE "资金记录ID" IN ({L(fund)},{L(new_fund)});
      DELETE FROM sales."客户档案表" WHERE "客户ID" IN ({L(customer)},{L(new_customer)}) OR "客户来源标识"={L(run)};
      DELETE FROM erp_ops.frontend_entry_audit a
       WHERE left(a.request_id,{len(run)})={L(run)}
          OR a.changes @> jsonb_build_array(jsonb_build_object('after',jsonb_build_object('客户ID',{L(customer)})))
          OR a.changes @> jsonb_build_array(jsonb_build_object('after',jsonb_build_object('资金记录ID',{L(fund)})))
          OR a.changes @> jsonb_build_array(jsonb_build_object('after',jsonb_build_object('资金记录ID',{L(new_fund)})))
          OR a.changes @> jsonb_build_array(jsonb_build_object('after',jsonb_build_object('客户来源标识',{L(run)})));
      COMMIT;''', db=demo)
    after = erp.data_signature(erp.c['database'])
    assert after == before, 'Formal business records changed'

result = json.loads(report.read_text(encoding='utf-8'))
result.update(at_utc=datetime.now(timezone.utc).isoformat(), test_rows_removed=True,
              direct_sql_verified=True, retry_audit_count=int(audit_count),
              create_retry_audit_count=int(new_audit_count), created_customer_count=int(created_count),
              formal_signature_before=before, formal_signature_after=after)
report.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
print('Direct SQL, exactly one retry audit, cleanup and formal data signature: PASS')
